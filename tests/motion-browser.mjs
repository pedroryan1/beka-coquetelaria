import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.BEKA_PLAYWRIGHT_PATH||'playwright');
const browser=await chromium.launch({channel:'msedge',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'no-preference'});
const page=await context.newPage();page.setDefaultTimeout(8000);
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const base='http://127.0.0.1:5173';
await page.goto(base+'/');await page.waitForSelector('.hero-content');
assert.equal(await page.locator('.hero-content h1').evaluate(el=>getComputedStyle(el).animationName),'beka-rise');
const card=page.locator('.menu-section .drink-card').first();
await page.waitForFunction(()=>document.querySelector('.menu-section .drink-card')?.dataset.motion==='observed');
await card.scrollIntoViewIfNeeded();
await page.waitForFunction(()=>document.querySelector('.menu-section .drink-card')?.dataset.motion==='visible');
await page.waitForFunction(()=>document.querySelector('.menu-section .drink-card')?.getAnimations().length===0);
assert.equal(await card.evaluate(el=>getComputedStyle(el).opacity),'1');
assert.equal(await card.evaluate(el=>getComputedStyle(el).transform),'none');
// Re-entering the viewport must not replay the reveal.
await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
await card.scrollIntoViewIfNeeded();
assert.equal(await card.evaluate(el=>el.getAnimations().length),0);
await page.goto(base+'/me-surpreenda');
await page.getByRole('button',{name:'Continuar',exact:true}).click();
assert.equal(await page.locator('.discovery-step').evaluate(el=>getComputedStyle(el).animationName),'beka-rise');
// A preference changed during use must also stop Web Animations API effects.
await page.emulateMedia({reducedMotion:'reduce'});
await page.waitForFunction(()=>document.getAnimations().length===0);
assert.equal(await page.locator('[data-motion]').count(),0);
await page.getByRole('button',{name:'Descobrir meu drink'}).click();
assert.equal(await page.locator('.result-card').evaluate(el=>getComputedStyle(el).animationName),'none');
await page.goto(base+'/');
assert.equal(await page.locator('.hero-content h1').evaluate(el=>getComputedStyle(el).animationName),'none');
assert.equal(await page.locator('.hero-content h1').evaluate(el=>getComputedStyle(el).opacity),'1');
assert.equal(await page.evaluate(()=>document.getAnimations().length),0);
await page.emulateMedia({reducedMotion:'no-preference'});
await page.waitForFunction(()=>document.querySelector('[data-motion]')!==null);
const touch=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,reducedMotion:'no-preference'});
const mobile=await touch.newPage();mobile.on('pageerror',e=>errors.push(e.message));
await mobile.goto(base+'/');
assert.equal(await mobile.locator('.hero-content h1').evaluate(el=>getComputedStyle(el).animationDuration),'0.5s');
assert.equal(await mobile.locator('.hero-photo').evaluate(el=>getComputedStyle(el).animationName),'beka-fade');
await mobile.getByRole('button',{name:'Abrir menu'}).tap();
await mobile.getByRole('navigation',{name:'Navegação principal'}).getByRole('link',{name:'Cardápio',exact:true}).tap();
await mobile.getByRole('button',{name:'Ver detalhes de Aurora Rosé'}).tap();
assert.equal(await mobile.getByRole('dialog').evaluate(el=>getComputedStyle(el).animationName),'beka-dialog');
await mobile.getByRole('button',{name:'Fechar',exact:true}).tap();
assert.equal(await mobile.getByRole('dialog').count(),0);
assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
assert.deepEqual(errors,[]);
console.log('PASS: entrada por rolagem sem repetição, etapas, movimento reduzido inicial e dinâmico, conteúdo sempre visível, efeitos de toque e modais no celular.');
await browser.close();
